\set ON_ERROR_STOP on

CREATE ROLE sr_app LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS CONNECTION LIMIT 8;
\password sr_app

CREATE DATABASE sr_metadata OWNER sr_app TEMPLATE template0;
REVOKE ALL ON DATABASE sr_metadata FROM PUBLIC;

\connect sr_metadata
GRANT EXECUTE ON FUNCTION pg_catalog.pg_control_system() TO sr_app;
