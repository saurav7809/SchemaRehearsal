CREATE TABLE project_baselines (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint REFERENCES projects ON DELETE SET NULL,
    source_run_id bigint UNIQUE REFERENCES test_runs ON DELETE SET NULL,
    name varchar(80) NOT NULL CHECK (length(btrim(name)) > 0),
    database_name varchar(44) NOT NULL UNIQUE CHECK (database_name ~ '^sr_baseline_[a-f0-9]{32}$'),
    created_at timestamptz NOT NULL DEFAULT now(),
    published boolean NOT NULL DEFAULT false
);

CREATE INDEX project_baselines_project ON project_baselines(project_id, id DESC)
    WHERE project_id IS NOT NULL;
