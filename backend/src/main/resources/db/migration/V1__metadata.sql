CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email varchar(254) UNIQUE NOT NULL,
    password_hash varchar(100) NOT NULL
);
CREATE TABLE projects (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id bigint NOT NULL REFERENCES accounts,
    name varchar(120) NOT NULL,
    description varchar(2000) NOT NULL,
    postgres_version varchar(20) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX projects_owner ON projects(owner_id);
CREATE TABLE database_configs (
    project_id bigint PRIMARY KEY REFERENCES projects ON DELETE CASCADE,
    host varchar(80) NOT NULL,
    port integer NOT NULL,
    database_name varchar(63) NOT NULL,
    username varchar(63) NOT NULL,
    encrypted_password text NOT NULL
);
CREATE TABLE migrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects ON DELETE CASCADE,
    name varchar(160) NOT NULL,
    sql_text text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX migrations_project ON migrations(project_id);
CREATE TABLE probes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects ON DELETE CASCADE,
    name varchar(120) NOT NULL,
    generation varchar(10) NOT NULL,
    sql_text text NOT NULL
);
CREATE TABLE test_runs (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id bigint NOT NULL REFERENCES projects ON DELETE CASCADE,
    migration_id bigint NOT NULL REFERENCES migrations ON DELETE CASCADE,
    migration_name varchar(160) NOT NULL,
    status varchar(20) NOT NULL,
    score integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    duration_ms bigint NOT NULL,
    report jsonb NOT NULL
);
CREATE INDEX runs_project ON test_runs(project_id, created_at DESC);
CREATE TABLE audit_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts,
    action varchar(40) NOT NULL,
    subject_id bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now()
);